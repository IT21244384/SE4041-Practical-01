// Combining strings with +
let firstName = "Kamal"
let lastName = "Perera"

let fullName = firstName + " " + lastName
print(fullName)

// String interpolation - \(value) inserts a value into the text
let name = "Kamal"
let age = 22
print("My name is \(name) and I am \(age) years old.")

let module = "SE4041"
let mark = 78
print("The student received \(mark) marks for \(module).")

